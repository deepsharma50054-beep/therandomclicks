const params = new URLSearchParams(window.location.search);
const key = params.get("collection") || "mountains";
const collection = collections[key] || collections.mountains;

document.getElementById("collectionEyebrow").textContent = collection.eyebrow;
document.getElementById("collectionTitle").textContent = collection.title;
document.getElementById("collectionDescription").textContent = collection.description;

const storySection = document.getElementById("collectionStory");
const storyGrid = document.getElementById("storyGrid");
const grid = document.getElementById("collectionGrid");
const lightbox = document.getElementById("lightbox");
const lightboxImage = document.getElementById("lightboxImage");
const lightboxTitle = document.getElementById("lightboxTitle");
const lightboxDescription = document.getElementById("lightboxDescription");
const lightboxClose = document.getElementById("lightboxClose");
const lightboxFullscreen = document.getElementById("lightboxFullscreen");
const lightboxPrev = document.getElementById("lightboxPrev");
const lightboxNext = document.getElementById("lightboxNext");

let currentIndex = 0;

const fullscreenElement =
  () => document.fullscreenElement || document.webkitFullscreenElement || null;

const fullscreenEnabled =
  () => Boolean(document.fullscreenEnabled || document.webkitFullscreenEnabled);

const requestElementFullscreen = async (element) => {
  if (element.requestFullscreen) {
    await element.requestFullscreen();
    return;
  }
  if (element.webkitRequestFullscreen) {
    element.webkitRequestFullscreen();
  }
};

const exitAnyFullscreen = async () => {
  if (document.exitFullscreen) {
    await document.exitFullscreen();
    return;
  }
  if (document.webkitExitFullscreen) {
    document.webkitExitFullscreen();
  }
};

const showImage = (index) => {
  if (!lightbox || !lightboxImage || !lightboxTitle || !lightboxDescription) return;

  const totalImages = collection.images.length;
  currentIndex = (index + totalImages) % totalImages;

  const [title, description, src] = collection.images[currentIndex];
  lightboxImage.src = src;
  lightboxImage.alt = title;
  lightboxTitle.textContent = title;
  lightboxDescription.textContent = description;
};

const openLightbox = async (index, shouldEnterFullscreen = false) => {
  if (!lightbox) return;
  showImage(index);
  lightbox.hidden = false;
  lightbox.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";

  if (shouldEnterFullscreen && fullscreenEnabled()) {
    try {
      await requestElementFullscreen(lightbox);
      updateFullscreenButton();
    } catch (error) {
      console.error("Opening fullscreen from collection tile failed", error);
    }
  }
};

const closeLightbox = async () => {
  if (!lightbox) return;

  if (fullscreenElement() === lightbox) {
    try {
      await exitAnyFullscreen();
    } catch (error) {
      console.error("Exiting fullscreen failed", error);
    }
  }

  lightbox.hidden = true;
  lightbox.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
};

const updateFullscreenButton = () => {
  if (!lightboxFullscreen) return;

  const isFullscreen = fullscreenElement() === lightbox;
  lightboxFullscreen.textContent = isFullscreen ? "⤢" : "⛶";
  lightboxFullscreen.setAttribute(
    "aria-label",
    isFullscreen ? "Exit fullscreen" : "Open fullscreen"
  );
};

const toggleFullscreen = async () => {
  if (!lightbox || !lightboxFullscreen || !fullscreenEnabled()) return;

  try {
    if (fullscreenElement() === lightbox) {
      await exitAnyFullscreen();
    } else {
      await requestElementFullscreen(lightbox);
    }
  } catch (error) {
    console.error("Fullscreen request failed", error);
  }
};

if (collection.story && storySection && storyGrid) {
  storySection.hidden = false;
  storyGrid.innerHTML = `
    <article class="story-card story-lead">
      <h2>Story of ${collection.title}</h2>
      <p>${collection.story.lead}</p>
    </article>
    <article class="story-card">
      <h3>Location</h3>
      <p>${collection.story.location}</p>
    </article>
    <article class="story-card">
      <h3>Historical Fact</h3>
      <p>${collection.story.historicalFact}</p>
    </article>
    <article class="story-card">
      <h3>Interesting Fact</h3>
      <p>${collection.story.interestingFact}</p>
    </article>
  `;
}

collection.images.forEach(([title, description, src], index) => {
  const figure = document.createElement("figure");
  figure.className = "collection-tile";
  figure.tabIndex = 0;
  figure.setAttribute("role", "button");
  figure.setAttribute("aria-label", `Open ${title} in gallery view`);
  figure.innerHTML = `
    <img src="${src}" alt="${title}" loading="lazy" decoding="async">
    <figcaption>
      <h3>${title}</h3>
      <p class="frame-note">${description}</p>
    </figcaption>
  `;
  figure.addEventListener("click", () => {
    openLightbox(index, true);
  });
  figure.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openLightbox(index, true);
    }
  });
  grid.appendChild(figure);
});

if (lightbox && lightboxClose && lightboxPrev && lightboxNext) {
  lightboxClose.addEventListener("click", closeLightbox);
  if (lightboxFullscreen) {
    if (fullscreenEnabled()) {
      lightboxFullscreen.addEventListener("click", toggleFullscreen);
      updateFullscreenButton();
    } else {
      lightboxFullscreen.hidden = true;
    }
  }
  lightboxPrev.addEventListener("click", () => showImage(currentIndex - 1));
  lightboxNext.addEventListener("click", () => showImage(currentIndex + 1));

  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) {
      closeLightbox();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (lightbox.hidden) return;

    if (event.key === "Escape") {
      closeLightbox();
    } else if (event.key === "ArrowLeft") {
      showImage(currentIndex - 1);
    } else if (event.key === "ArrowRight") {
      showImage(currentIndex + 1);
    }
  });

  document.addEventListener("fullscreenchange", updateFullscreenButton);
  document.addEventListener("webkitfullscreenchange", updateFullscreenButton);
}
